export function t(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let out = STRINGS[locale][key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v));
  return out;
}
